def run(test_selector):
    """跑一个用例，返回 (是否通过, 是否真的跑了)。"""
    class_name, method = test_selector.rsplit(".", 1)
    path = os.path.join(ROOT, "app/build/test-results/testDebugUnitTest/TEST-%s.xml" % class_name)
    # 先删掉旧结果：否则编译失败时会读到上一轮的绿
    if os.path.exists(path):
        os.remove(path)
    subprocess.run(["./gradlew", ":app:testDebugUnitTest", "--tests", test_selector,
                    "--console=plain"], cwd=ROOT, env=ENV,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if not os.path.exists(path):
        return False, False
    root = ET.parse(path).getroot()
    for case in root.iter("testcase"):
        if case.get("name") == method:
            broken = any(child.tag in ("failure", "error") for child in case)
            return not broken, True
    return False, False


def main():
    backups = {}
    # 从 MUTATIONS 里推导要备份哪些文件：加了新目标文件不用再记着改这里
    # （之前忘了加 ServerBall.java，跑一半 KeyError 挂掉）。
    for path in sorted({path for _, path, _, _, _ in MUTATIONS}):
        source = os.path.join(ROOT, path)
        backups[path] = open(source, encoding="utf-8").read()

    problems = []
    try:
        for name, path, old, new, selector in MUTATIONS:
            source = os.path.join(ROOT, path)
            text = backups[path]
            olds = old if isinstance(old, list) else [old]
            news = new if isinstance(new, list) else [new]
            # 一条变异可以是"多处一起改回"（用来还原有两道保险的修复）
            miss = [o for o in olds if text.count(o) != 1]
            if miss:
                problems.append("%s：找不到唯一的锚点（%s）" % (name, [text.count(o) for o in miss]))
                continue
            for o, n in zip(olds, news):
                text = text.replace(o, n)
            open(source, "w", encoding="utf-8").write(text)
            passed, ran = run(selector)
            verdict = "变红 ✓" if (ran and not passed) else ("用例没跑到 ✗" if not ran else "还是绿的 ✗")
            print("%-46s %-28s %s" % (name, selector.rsplit(".", 1)[1], verdict))
            if not ran or passed:
                problems.append(name)
            open(source, "w", encoding="utf-8").write(backups[path])
    finally:
        for path, text in backups.items():
            open(os.path.join(ROOT, path), "w", encoding="utf-8").write(text)

    print()
    print("全部变异都变红了 ✓" if not problems else "有问题：%s" % problems)
    return 1 if problems else 0


if __name__ == "__main__":
    if sys.argv[1:] == ["--list"]:
        for name, *_ in MUTATIONS:
            print(name)
        sys.exit(0)
    sys.exit(main())
